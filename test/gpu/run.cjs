// Runs the GPU spec (cc.webgl.test.ts) through a SafeLight checkout's WebGL test
// harness — headless Chromium on SwiftShader, the real renderer, the real stage
// injection — so the shader is verified where the CPU suite cannot see:
// compilation inside the develop program, uniform namespacing and binding,
// and the rendered result against the model.
//
// The spec is copied into the checkout for the run (its harness helpers and
// path aliases only resolve from inside) and removed again afterwards, along
// with the generated config. Point SAFELIGHT_CORE at the checkout; by default a
// `SafeLight` directory beside this repository or beside its parent folder is
// used. SAFELIGHT_TEST_CHROME overrides the browser executable when
// Playwright's bundled Chromium will not start. The browser server takes a
// port the OS hands out rather than vitest's fixed default, which Windows'
// dynamic port exclusions can swallow.
"use strict";

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "SafeLight"), path.join(extension, "..", "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No SafeLight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", "__cc_gpu__");
const specFile = path.join(specDir, "cc.webgl.test.ts");
const configFile = path.join(core, "vitest.cc-gpu.config.ts");
const executablePath = process.env.SAFELIGHT_TEST_CHROME;

const config = (port) => `/// <reference types="vitest/config" />
// Generated by the Colour Correction extension's test/gpu/run.cjs — removed
// after the run. Same rig as vitest.webgl.config.ts, plus the extension's
// sources and its copied spec.
import path from "path";
import { readFileSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-cc-gpu",
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@cc": path.join(EXT, "src"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "cc-gpu",
    include: ["src/rendering/webgl/__cc_gpu__/*.webgl.test.ts"],
    testTimeout: 300_000,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright(),
      api: { port: ${port}, strictPort: true },
      instances: [
        {
          browser: "chromium",
          launch: {
            ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
            args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
          },
        },
      ],
    },
  },
});
`;

// A failing browser run drops screenshots under the checkout's
// .vitest-attachments; clear it afterwards unless it was already there.
const attachments = path.join(core, ".vitest-attachments");
const hadAttachments = fs.existsSync(attachments);

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

async function main() {
  const port = await freePort();
  let status = 1;
  try {
    fs.mkdirSync(specDir, { recursive: true });
    fs.copyFileSync(path.join(__dirname, "cc.webgl.test.ts"), specFile);
    fs.writeFileSync(configFile, config(port));
    const result = spawnSync("npx", ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"], {
      cwd: core,
      stdio: "inherit",
      shell: true,
    });
    status = result.status ?? 1;
  } finally {
    fs.rmSync(specDir, { recursive: true, force: true });
    fs.rmSync(configFile, { force: true });
    if (!hadAttachments) fs.rmSync(attachments, { recursive: true, force: true });
  }
  process.exit(status);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
